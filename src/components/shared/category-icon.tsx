export function iconByName(name: string | null | undefined): LucideIcon {
  return (name && ICONS[name]) || Ellipsis;
}

interface CategoryIconProps {
  icon?: string | null;
  color?: string | null;
  size?: "xs" | "sm" | "md" | "lg";
  className?: string;
}

const SIZES = {
  xs: "size-6 rounded-[7px] [&_svg]:size-3.5",
  sm: "size-8 rounded-[9px] [&_svg]:size-4",
  md: "size-10 rounded-[11px] [&_svg]:size-[18px]",
  lg: "size-12 rounded-[13px] [&_svg]:size-5",
};

/** Category glyph on a tinted tile of the category colour. Decorative: the name is always shown next to it. */
export function CategoryIcon({ icon, color, size = "md", className }: CategoryIconProps) {
  const c = color ?? "var(--ink-3)";
  return (
    <span
      aria-hidden
      className={cn("grid shrink-0 place-items-center", SIZES[size], className)}
      style={{ backgroundColor: `color-mix(in srgb, ${c} 16%, transparent)`, color: `color-mix(in srgb, ${c} 82%, var(--ink))` }}
    >
      {React.createElement(iconByName(icon), { strokeWidth: 2 })}
    </span>
  );
}
